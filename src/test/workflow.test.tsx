import { beforeEach, expect, it, vi } from 'vitest';
import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import App from '../App';
vi.mock('../lib/config', () => ({ demoMode: true, setupMissing: false, apiBase: '', supabaseUrl: '', supabaseKey: '' }));
vi.mock('../lib/supabase', () => ({ supabase: null }));
beforeEach(() => { localStorage.clear(); window.history.replaceState({}, '', '/'); });
it('completes the student demo flow with Bengali text, confirmation, persistence and ungraded feedback', async () => {
  const user = userEvent.setup(); render(<App/>);
  await user.click(await screen.findByRole('link', { name: 'New session' }));
  await user.selectOptions(await screen.findByLabelText('Conversation language'), 'bn');
  await user.click(screen.getByRole('button', { name: 'Begin consultation' }));
  expect(await screen.findByRole('heading', { name: 'Samira Ahmed' })).toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Submit diagnosis' })).toBeDisabled();
  await user.type(screen.getByLabelText('Your message to the patient'), 'আপনার ঘুম কেমন হচ্ছে?');
  await user.click(screen.getByRole('button', { name: 'Send message' }));
  expect(await screen.findByText('আপনার ঘুম কেমন হচ্ছে?')).toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Submit diagnosis' })).toBeDisabled();
  for (let i = 0; i < 6; i++) await user.click(screen.getAllByRole('button', { name: 'Demo: mark explored' })[0]);
  await user.click(screen.getByRole('button', { name: 'Submit diagnosis' }));
  await user.type(screen.getByLabelText('Diagnosis', { exact: true }), 'বিষণ্নতা');
  await user.click(screen.getByRole('button', { name: 'Review submission' }));
  expect(screen.getByRole('heading', { name: 'Confirm your final diagnosis' })).toBeInTheDocument();
  await user.click(screen.getByRole('button', { name: 'Confirm & submit' }));
  expect(await screen.findByRole('heading', { name: 'Review required' })).toBeInTheDocument();
  expect(screen.getByText('বিষণ্নতা')).toBeInTheDocument();
  expect(screen.getByText('Not available — review required')).toBeInTheDocument();
  await user.click(screen.getByRole('link', { name: 'Back to practice history' }));
  await waitFor(() => expect(screen.getByText('Review required')).toBeInTheDocument());
}, 20000);
